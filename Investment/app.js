function buildSukanyaRecordEditorRow(record) {
  const row = document.createElement("tr");
  const normalizedRecord = normalizeSukanyaRecord(record);
  [
    "s_no",
    "value_date",
    "transaction_date",
    "cheque_number",
    "transaction_remarks",
    "withdrawal_amount_inr",
    "deposit_amount_inr",
    "interest_deposited_inr",
    "interest_received",
    "balance_inr"
  ].forEach((field) => {
    const cell = document.createElement("td");
    const input = document.createElement(field === "transaction_remarks" ? "textarea" : "input");
    if (field !== "transaction_remarks") {
      input.type = "text";
    }
    input.value = field === "interest_received" ? "" : normalizedRecord[field] || "";
    input.dataset.field = field;
    input.className = "esop-table-input";
    input.placeholder = getSukanyaFieldPlaceholder(field);
    if (field === "interest_received" || field === "balance_inr") {
      input.readOnly = true;
      input.classList.add("esop-table-input-readonly");
    }
    cell.append(input);
    row.append(cell);
  });

  const actionCell = document.createElement("td");
  const removeButton = document.createElement("button");
  removeButton.type = "button";
  removeButton.className = "ghost";
  removeButton.textContent = "Remove";
  removeButton.addEventListener("click", () => {
    row.remove();
    refreshSukanyaEditorInterest(row.closest("table"));
  });
  actionCell.append(removeButton);
  row.append(actionCell);

  row.addEventListener("input", () => {
    refreshSukanyaEditorInterest(row.closest("table"));
  });

  return row;
}

