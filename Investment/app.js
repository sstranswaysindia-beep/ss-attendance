  const normalizedRecords = getSukanyaDisplayRecords(records).map(({ interest_received, ...record }) => record);

  const totalDeposit = normalizedRecords.reduce((sum, record) => sum + parseLooseNumber(record.deposit_amount_inr), 0);
  const totalInterest = normalizedRecords.reduce((sum, record) => sum + parseLooseNumber(record.interest_deposited_inr), 0);
  const totalWithdrawal = normalizedRecords.reduce((sum, record) => sum + parseLooseNumber(record.withdrawal_amount_inr), 0);
  const latestBalance =
    normalizedRecords
      .map((record) => String(record.balance_inr || "").trim())
