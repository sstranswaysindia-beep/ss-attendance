function buildEsopRecordEditorRow(record) {
  const row = document.createElement("tr");

  [
    "s_no",
    "year",
    "investment",
    "remarks",
    "euro_alloted",
    "maturity_date",
    "expected_return",
    "amount_received",
    "return_received"
  ].forEach((field) => {
    const cell = document.createElement("td");
    const input = document.createElement(field === "remarks" ? "textarea" : "input");
    if (field !== "remarks") {
      input.type = "text";
    }
    input.value =
      field === "return_received"
        ? calculateReturnReceived(record.investment, record.amount_received)
        : record[field] || "";
    input.dataset.field = field;
    input.className = "esop-table-input";
    input.placeholder = getEsopFieldPlaceholder(field);
    if (field === "return_received") {
      input.readOnly = true;
      input.classList.add("esop-table-input-readonly");
    }
    cell.append(input);
    row.append(cell);
  });

  const actionCell = document.createElement("td");
  const removeButton = document.createElement("button");
  removeButton.type = "button";
  removeButton.className = "ghost";
  removeButton.textContent = "Remove";
  removeButton.addEventListener("click", () => {
    row.remove();
  });
  actionCell.append(removeButton);
  row.append(actionCell);

  attachEsopRowCalculator(row);

  return row;
}

