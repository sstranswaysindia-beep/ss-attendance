function createLifeInsuranceDocumentCell(rowIndex, field, value) {
  const cell = document.createElement("td");
  const wrap = document.createElement("div");
  wrap.className = "doc-cell";

  const text = document.createElement("button");
  text.type = "button";
  text.className = "doc-cell-value";
  let trimmedValue = String(value || "").trim();
  const renderText = (nextValue) => {
    trimmedValue = String(nextValue || "").trim();
    text.className = "doc-cell-value";
    if (trimmedValue) {
      text.textContent = trimmedValue.split("/").at(-1) || trimmedValue;
    } else {
      text.textContent = "Upload / note";
      text.classList.add("inline-editable-placeholder");
    }
  };
  renderText(trimmedValue);

  text.addEventListener("click", () => {
    if (wrap.dataset.editing === "true") {
      return;
    }
    wrap.dataset.editing = "true";
    const input = document.createElement("input");
    input.type = "text";
    input.className = "esop-table-input inline-cell-input";
    input.value = trimmedValue;
    wrap.replaceChild(input, text);
    input.focus();
    input.select();

    let finished = false;
    const finish = async (shouldSave) => {
      if (finished) {
        return;
      }
      finished = true;
      wrap.dataset.editing = "false";

      const nextValue = input.value.trim();
      wrap.replaceChild(text, input);

      if (!shouldSave || nextValue === trimmedValue) {
        renderText(trimmedValue);
        return;
      }

      try {
        await saveLifeInsuranceInlineCell(rowIndex, field, nextValue);
      } catch (error) {
        renderText(trimmedValue);
        showCopyToast(error.message || "Save failed");
      }
    };

    input.addEventListener("blur", () => finish(true));
    input.addEventListener("keydown", (event) => {
      if (event.key === "Enter") {
        event.preventDefault();
        finish(true);
      }
      if (event.key === "Escape") {
        event.preventDefault();
        finish(false);
      }
    });
  });

  const actions = document.createElement("div");
  actions.className = "doc-cell-actions";

  const uploadLabel = document.createElement("label");
  uploadLabel.className = "mini-upload";
  uploadLabel.textContent = "Upload";
  const input = document.createElement("input");
  input.type = "file";
  input.hidden = true;
  input.addEventListener("change", async () => {
    const file = input.files?.[0];
    if (!file) {
      return;
    }
    try {
      await handleLifeInsuranceFileUpload(rowIndex, field, file);
    } catch (error) {
      showCopyToast(error.message || "Upload failed");
    } finally {
      input.value = "";
    }
  });
  uploadLabel.append(input);
  actions.append(uploadLabel);

  if (trimmedValue) {
    const previewButton = document.createElement("button");
    previewButton.type = "button";
    previewButton.className = "ghost mini-preview";
    previewButton.textContent = "Preview";
    previewButton.addEventListener("click", () => {
      setLifeInsurancePreview(field === "policy_document" ? "Policy Document" : "Policy Receipt", trimmedValue);
    });
    actions.append(previewButton);
  }

  wrap.append(text, actions);
  cell.append(wrap);
  return cell;
}

