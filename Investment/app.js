function buildNpsRecordEditorRow(record) {
  const normalizedRecord = normalizeNpsRecord(record);
  const row = document.createElement("tr");

  ["name", "amount", "note"].forEach((field) => {
    const cell = document.createElement("td");
    const input = document.createElement(field === "note" ? "textarea" : "input");
    if (field !== "note") {
      input.type = "text";
    }
    input.value = normalizedRecord[field] || "";
    input.dataset.field = field;
    input.className = "esop-table-input";
    cell.append(input);
    row.append(cell);
  });

  const actionCell = document.createElement("td");
  const removeButton = document.createElement("button");
  removeButton.type = "button";
  removeButton.className = "ghost";
  removeButton.textContent = "Remove";
  removeButton.addEventListener("click", () => {
    row.remove();
  });
  actionCell.append(removeButton);
  row.append(actionCell);
  return row;
}

function getBlankNpsRecord() {
  return {
    name: "",
    amount: "",
    note: ""
  };
}

function focusNpsEditorRow(rowIndex) {
  if (typeof rowIndex !== "number" || rowIndex < 0) {
    return;
  }

  requestAnimationFrame(() => {
    const rows = tabContent?.querySelectorAll("tbody tr");
    const targetRow = rows?.[rowIndex];
    const firstInput = targetRow?.querySelector(".esop-table-input");
    if (firstInput) {
      firstInput.focus();
      targetRow.scrollIntoView({ behavior: "smooth", block: "center" });
    }
  });
}

