function parseStatementAmount(value) {
  const text = String(value || "").trim();
  if (!text) {
    return null;
  }

  const negative = /^\(.*\)$/.test(text) || text.startsWith("-");
  const cleaned = text.replace(/[^0-9.]/g, "");
  if (!cleaned) {
    return null;
  }

  const amount = Number.parseFloat(cleaned);
  if (!Number.isFinite(amount)) {
    return null;
  }

  return negative ? -amount : amount;
}

function formatStatementCurrency(value, options = {}) {
  const amount = parseStatementAmount(value);
  if (amount === null) {
    return String(value || "").trim();
  }

  if (options.short) {
    return `${amount < 0 ? "-" : ""}${formatIndianCurrencyShort(Math.abs(amount))}`;
  }

  return `${amount < 0 ? "-₹ " : "₹ "}${formatIndianNumber(Math.abs(amount))}`;
}

