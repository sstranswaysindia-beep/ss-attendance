function groupEsopAccounts(accounts) {
  return accounts.reduce((groups, item) => {
    if (!groups[item.group]) {
      groups[item.group] = [];
    }
    groups[item.group].push(item);
    return groups;
  }, {});
}

async function saveEsopInlineCell(rowIndex, field, value) {
  const source = esopDataCache || getEsopFallbackData();
  const working = withTrailingBlankRow(source.records || [], ESOP_INLINE_EDITABLE_FIELDS, getBlankEsopRecord).map((record) => ({
    ...record
  }));

  working[rowIndex] = working[rowIndex] || getBlankEsopRecord(rowIndex + 1);
  working[rowIndex][field] = value;

  const records = sanitizeInlineRecords(working, ESOP_INLINE_EDITABLE_FIELDS);
  const savedData = await saveEsopData({
    accounts: source.accounts,
    records
  });

  esopDataCache = savedData;
  if (currentProfileKey === "neeraj" && profiles[currentProfileKey]) {
    renderHeroStats(profiles[currentProfileKey]);
  }
  showCopyToast("ESOP saved to CSV");
  renderEsopViewer(savedData);
}

