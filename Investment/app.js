function getProfileImageCandidates(profile, profileKey) {
  const candidates = [];
  const firstName = getProfileFirstName(profile);
  const rawFirstName = String(profile?.name || "")
    .trim()
    .split(/\s+/)
    .filter(Boolean)[0] || "";
  const baseNames = [firstName, rawFirstName, profileKey].filter(Boolean);
  const extensions = ["png", "jpg", "jpeg", "webp", "gif", "svg", "avif"];

  if (profile?.photo) {
    candidates.push(profile.photo);
  }

  baseNames.forEach((baseName) => {
    extensions.forEach((extension) => {
      candidates.push(`profiles/${baseName}.${extension}`);
    });
  });

  return [...new Set(candidates)];
}

function applyProfilePhoto(imageNode, fallbackNode, profile, profileKey) {
  if (!imageNode || !fallbackNode) {
    return;
  }

  const initials = getProfileInitials(profile?.name);
  fallbackNode.textContent = initials;
  fallbackNode.hidden = false;

  if (!profile || !profileKey) {
    imageNode.hidden = true;
    imageNode.removeAttribute("src");
    imageNode.alt = "";
    fallbackNode.hidden = false;
    return;
  }

  const candidateSources = getProfileImageCandidates(profile, profileKey);
  let sourceIndex = 0;

  const tryNextSource = () => {
    const nextSource = candidateSources[sourceIndex];
    sourceIndex += 1;

    if (!nextSource) {
      imageNode.hidden = true;
      imageNode.removeAttribute("src");
      fallbackNode.hidden = false;
      return;
    }

    imageNode.hidden = false;
    imageNode.src = nextSource;
  };

  imageNode.alt = `${profile.name} profile photo`;
  imageNode.onerror = () => {
    fallbackNode.hidden = false;
    tryNextSource();
  };
  imageNode.onload = () => {
    imageNode.hidden = false;
    fallbackNode.hidden = true;
  };

  tryNextSource();
}

