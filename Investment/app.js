async function fetchNpsData(profileKey) {
  try {
    const response = await fetch(`nps_data.php?profile=${encodeURIComponent(profileKey)}&ts=${Date.now()}`);
    if (!response.ok) {
      throw new Error("Unable to load NPS details.");
    }

    const payload = await response.json();
    if (!payload.ok) {
      throw new Error(payload.error || "Unable to load NPS details.");
    }

    npsStorageModeByProfile[profileKey] = "backend";
    persistNpsToLocalStorage(profileKey, payload);
    return payload;
  } catch {
    npsStorageModeByProfile[profileKey] = "local";
    return getNpsFallbackData(profileKey);
  }
}

async function saveNpsData(profileKey, payload) {
  try {
    const response = await fetch(`nps_data.php?profile=${encodeURIComponent(profileKey)}`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify(payload)
    });

    if (!response.ok) {
      throw new Error("Unable to save NPS details.");
    }

    const data = await response.json();
    if (!data.ok) {
      throw new Error(data.error || "Unable to save NPS details.");
    }

    npsStorageModeByProfile[profileKey] = "backend";
    persistNpsToLocalStorage(profileKey, data);
    return data;
  } catch {
    npsStorageModeByProfile[profileKey] = "local";
    throw new Error("Backend not reachable. NPS CSV was not updated. Open this page through a PHP server or hosting path.");
  }
}

