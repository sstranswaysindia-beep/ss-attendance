function hasInlineRowContent(record, fields) {
  return fields.some((field) => String(record?.[field] || "").trim() !== "");
}

function withTrailingBlankRow(records, fields, getBlankRow) {
  const working = records.map((record, index) => ({
    ...record,
    s_no: String(index + 1)
  }));

  if (!working.length || hasInlineRowContent(working.at(-1), fields)) {
    working.push(getBlankRow(working.length + 1));
  }

  return working.map((record, index) => ({
    ...record,
    s_no: String(index + 1)
  }));
}

function sanitizeInlineRecords(records, fields) {
  return records
    .filter((record) => hasInlineRowContent(record, fields))
    .map((record, index) => ({
      ...record,
      s_no: String(index + 1)
    }));
}

function createInlineEditableCell({
  rowIndex,
  field,
  value,
  editable,
  onCommit,
  placeholder = "Click to edit"
}) {
  const cell = document.createElement("td");
  cell.className = editable ? "inline-editable-cell" : "inline-readonly-cell";

  const renderValue = (nextValue) => {
    cell.replaceChildren();
    const display = document.createElement("span");
    const text = String(nextValue || "").trim();
    display.textContent = text || (editable ? placeholder : "");
    if (!text && editable) {
      display.className = "inline-editable-placeholder";
    }
    cell.append(display);
  };

  renderValue(value);

  if (!editable) {
    return cell;
  }

  cell.tabIndex = 0;
  cell.title = "Click to edit this cell";

  const openEditor = () => {
    if (cell.dataset.editing === "true") {
      return;
    }

    cell.dataset.editing = "true";
    cell.replaceChildren();

    const input = document.createElement("input");
    input.type = "text";
    input.className = "esop-table-input inline-cell-input";
    input.value = value || "";
    cell.append(input);
    input.focus();
    input.select();

    let finished = false;
    const finish = async (shouldSave) => {
      if (finished) {
        return;
      }
      finished = true;
      cell.dataset.editing = "false";

      if (!shouldSave) {
        renderValue(value);
        return;
      }

      const nextValue = input.value.trim();
      if (nextValue === String(value || "").trim()) {
        renderValue(value);
        return;
      }

      input.disabled = true;

      try {
        await onCommit(rowIndex, field, nextValue);
      } catch (error) {
        renderValue(value);
        showCopyToast(error.message || "Save failed");
      }
    };

    input.addEventListener("blur", () => {
      finish(true);
    });

    input.addEventListener("keydown", (event) => {
      if (event.key === "Enter") {
        event.preventDefault();
        finish(true);
      }
      if (event.key === "Escape") {
        event.preventDefault();
        finish(false);
      }
    });
  };

  cell.addEventListener("click", openEditor);
  cell.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      openEditor();
    }
  });

  return cell;
}

