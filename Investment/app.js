function getEsopFieldPlaceholder(field) {
  const placeholders = {
    s_no: "S.No",
    year: "2024",
    investment: "50,000",
    remarks: "Remarks / notes",
    euro_alloted: "250.00",
    maturity_date: "2029",
    expected_return: "5x",
    amount_received: "Amount received",
    return_received: "Auto"
  };
  return placeholders[field] || "";
}

function attachEsopRowCalculator(row) {
  const investmentInput = row.querySelector('[data-field="investment"]');
  const amountReceivedInput = row.querySelector('[data-field="amount_received"]');
  const returnReceivedInput = row.querySelector('[data-field="return_received"]');

  if (!investmentInput || !amountReceivedInput || !returnReceivedInput) {
    return;
  }

  const refreshReturn = () => {
    returnReceivedInput.value = calculateReturnReceived(investmentInput.value, amountReceivedInput.value);
  };

  investmentInput.addEventListener("input", refreshReturn);
  amountReceivedInput.addEventListener("input", refreshReturn);
  refreshReturn();
}

function focusEsopEditorRow(rowIndex) {
  if (typeof rowIndex !== "number" || rowIndex < 0) {
    return;
  }

  requestAnimationFrame(() => {
    const rows = tabContent?.querySelectorAll("tbody tr");
    const targetRow = rows?.[rowIndex];
    const firstInput = targetRow?.querySelector(".esop-table-input");
    if (firstInput) {
      firstInput.focus();
      targetRow.scrollIntoView({ behavior: "smooth", block: "center" });
    }
  });
}

