function formatIndianCurrencyShort(value) {
  const amount = Number(value) || 0;
  if (amount >= 10000000) {
    return `₹ ${(amount / 10000000).toFixed(2)} Cr`;
  }
  if (amount >= 100000) {
    return `₹ ${(amount / 100000).toFixed(2)} L`;
  }
  if (amount >= 1000) {
    return `₹ ${(amount / 1000).toFixed(1)} K`;
  }
  return `₹ ${amount.toFixed(0)}`;
}

function parseLooseNumber(value) {
  const parsed = Number.parseFloat(String(value || "0").replace(/,/g, ""));
  return Number.isFinite(parsed) ? parsed : 0;
}

function formatIndianNumber(value) {
  return numberFormatter.format(Math.round(Number(value) || 0));
}

function extractReturnMultiplier(value) {
  const match = String(value || "")
    .toLowerCase()
    .match(/(\d+(?:\.\d+)?)\s*x/);
  return match ? Number.parseFloat(match[1]) : 0;
}

function calculateReturnReceived(investment, amountReceived) {
  const principal = parseLooseNumber(investment);
  const received = parseLooseNumber(amountReceived);

  if (!principal || !received) {
    return "";
  }

  const multiple = received / principal;
  const rounded = Number.isInteger(multiple) ? multiple.toFixed(0) : multiple.toFixed(2);
  return `${rounded}x`;
}

function formatPercent(value) {
  const numeric = Number(value);
  if (!Number.isFinite(numeric) || numeric <= 0) {
    return "";
  }
  return `${numeric.toFixed(2).replace(/\.00$/, "").replace(/(\.\d)0$/, "$1")}%`;
}

