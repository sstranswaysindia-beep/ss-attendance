function refreshPpfEditorCalculations(table) {
  const rows = table?.querySelectorAll("tbody tr");
  if (!rows?.length) {
    return;
  }

  let previousBalance = 0;
  let previousInterestReceived = 0;

  rows.forEach((row) => {
    const withdrawalInput = row.querySelector('[data-field="withdrawal_amount_inr"]');
    const depositInput = row.querySelector('[data-field="deposit_amount_inr"]');
    const balanceInput = row.querySelector('[data-field="balance_inr"]');
    const interestBankInput = row.querySelector('[data-field="interest_received_in_bank"]');
    const interestActualInput = row.querySelector('[data-field="interest_actual"]');
    const interestPercentInput = row.querySelector('[data-field="interest_percent"]');
    const record = {
      value_date: row.querySelector('[data-field="value_date"]')?.value,
      transaction_date: row.querySelector('[data-field="transaction_date"]')?.value,
      transaction_remarks: row.querySelector('[data-field="transaction_remarks"]')?.value,
      withdrawal_amount_inr: withdrawalInput?.value,
      deposit_amount_inr: depositInput?.value
    };

    const balanceValue = calculatePpfBalance(previousBalance, previousInterestReceived, record);
    if (balanceInput) {
      balanceInput.value = balanceValue;
    }
    if (interestActualInput) {
      interestActualInput.value = calculatePpfInterestActual(balanceValue);
    }
    if (interestPercentInput) {
      interestPercentInput.value = calculatePpfInterestPercent(balanceValue, interestBankInput?.value);
    }

    if (balanceValue !== "") {
      previousBalance = parseLooseNumber(balanceValue);
      previousInterestReceived = parseLooseNumber(interestBankInput?.value);
    }
  });
}

